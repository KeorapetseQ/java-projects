    private void handlePolicyCreation(java.awt.event.ActionEvent evt) {
        int activeTab = jTabbedPane1.getSelectedIndex();
        switch (activeTab) {
            case 0: createMotorPolicy(); break;
            case 1: createPropertyPolicy(); break;
            case 2: createLifePolicy(); break;
            case 3: createHealthPolicy(); break;
        }
    }
    
    private void createMotorPolicy() {
        try {
            String customerId = jTextField1.getText().trim();
            String startDate = jTextField2.getText().trim();
            String endDate = jTextField3.getText().trim();
            double coverage = Double.parseDouble(jTextField4.getText().trim());

            String regNo = jTextField12.getText().trim();
            String make = jTextField13.getText().trim();
            String model = jTextField14.getText().trim();
            double vehicleValue = Double.parseDouble(jTextField15.getText().trim());
            String vehicleType = jComboBox3.getSelectedItem().toString();
            String coverType = jComboBox4.getSelectedItem().toString();

            double riskRate = coverType.equalsIgnoreCase("Comprehensive") ? 0.05 : 0.02;
            double annualPremium = vehicleValue * riskRate;
            String policyNumber = "POL-" + System.currentTimeMillis() % 100000;

            try (Connection conn = DBConnection.getConnection();
                 PreparedStatement pstmt1 = conn.prepareStatement("INSERT INTO policies (policy_number, customer_id, policy_type, start_date, end_date, coverage_amount, annual_premium, status) VALUES (?, ?, 'MOTOR', ?, ?, ?, ?, 'ACTIVE')");
                 PreparedStatement pstmt2 = conn.prepareStatement("INSERT INTO motor_policies (policy_number, registration_number, make, model, manufacture_year, vehicle_value, vehicle_type, cover_type) VALUES (?, ?, ?, ?, 2020, ?, ?, ?)")) {
                
                pstmt1.setString(1, policyNumber);
                pstmt1.setString(2, customerId);
                pstmt1.setDate(3, java.sql.Date.valueOf(startDate));
                pstmt1.setDate(4, java.sql.Date.valueOf(endDate));
                pstmt1.setDouble(5, coverage);
                pstmt1.setDouble(6, annualPremium);
                pstmt1.executeUpdate();

                pstmt2.setString(1, policyNumber);
                pstmt2.setString(2, regNo);
                pstmt2.setString(3, make);
                pstmt2.setString(4, model);
                pstmt2.setDouble(5, vehicleValue);
                pstmt2.setString(6, vehicleType);
                pstmt2.setString(7, coverType);
                pstmt2.executeUpdate();

                javax.swing.JOptionPane.showMessageDialog(this, "Motor Policy created successfully! Annual Premium: M" + annualPremium);
                new Thread(() -> EmailService.sendPolicyEmail(customerId, policyNumber, "MOTOR", annualPremium)).start();
                this.dispose();
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error creating motor policy: " + e.getMessage());
        }
    }

