    private void showMessage(String message) {
        javax.swing.JOptionPane.showMessageDialog(this, message);
    }

    private void submitClaim() {
        String policyNumber = jTextField1.getText().trim();
        String amountText = jTextField2.getText().trim();
        String description = jTextField3.getText().trim();
        
        if (policyNumber.isEmpty()) {
            showMessage("Please enter the policy number.");
            return;
        }
        if (amountText.isEmpty()) {
            showMessage("Please enter the claim amount.");
            return;
        }
        double amount;
        try {
            amount = Double.parseDouble(amountText);
        } catch (NumberFormatException ex) {
            showMessage("Please enter a valid number for the claim amount.");
            return;
        }
        if (amount <= 0) {
            showMessage("The claim amount must be greater than zero.");
            return;
        }
        if (description.isEmpty()) {
            showMessage("Please describe the claim.");
            return;
        }

        try (Connection conn = DBConnection.getConnection()) {
            // The policy must exist; the customer is taken from the policy
            String customerId;
            try (PreparedStatement ps = conn.prepareStatement(
                    "SELECT customer_id, status FROM policies WHERE policy_number = ?")) {
                ps.setString(1, policyNumber);
                try (ResultSet rs = ps.executeQuery()) {
                    if (!rs.next()) {
                        showMessage("Policy '" + policyNumber + "' was not found.\nPlease check the policy number.");
                        return;
                    }
                    customerId = rs.getString("customer_id");
                    String status = rs.getString("status");
                    if ("EXPIRED".equalsIgnoreCase(status) || "CANCELLED".equalsIgnoreCase(status)) {
                        showMessage("Policy '" + policyNumber + "' is " + status
                                + ".\nClaims cannot be submitted against it.");
                        return;
                    }
                }
            }

            String claimNumber = generateClaimNumber(conn);

            try (PreparedStatement ps = conn.prepareStatement(
                    "INSERT INTO claims (claim_number, policy_number, customer_id, date_submitted, claim_amount, description, status) "
                    + "VALUES (?, ?, ?, ?, ?, ?, 'SUBMITTED')")) {
                ps.setString(1, claimNumber);
                ps.setString(2, policyNumber);
                ps.setString(3, customerId);
                ps.setDate(4, java.sql.Date.valueOf(java.time.LocalDate.now()));
                ps.setDouble(5, amount);
                ps.setString(6, description);
                ps.executeUpdate();
            }

            showMessage("Claim submitted successfully!\n\nClaim number: " + claimNumber
                    + "\nPolicy number: " + policyNumber
                    + "\nStatus: SUBMITTED\n\nThe Claims Officer can now assess it.");

            jTextField1.setText("");
            jTextField2.setText("");
            jTextField3.setText("");
            loadClaims();

        } catch (SQLException ex) {
            showMessage("Error submitting claim: " + ex.getMessage());
        }
    }

    /** Builds a claim number such as CLA-4821 that is not already in the database. */
    private String generateClaimNumber(Connection conn) throws SQLException {
        for (int attempt = 0; attempt < 20; attempt++) {
            String candidate = "CLA-" + (1000 + RANDOM.nextInt(9000));
            try (PreparedStatement ps = conn.prepareStatement("SELECT 1 FROM claims WHERE claim_number = ?")) {
                ps.setString(1, candidate);
                try (ResultSet rs = ps.executeQuery()) {
                    if (!rs.next()) {
                        return candidate;
                    }
                }
            }
        }
        return "CLA-" + System.currentTimeMillis() % 1000000;
    }

    /** Fills the table (tblClaims) with the latest claims. */
    private void loadClaims() {
        DefaultTableModel model = new DefaultTableModel(
                new String[]{"Claim Number", "Policy Number", "Claim Amount", "Status", "Date Submitted"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;   // read-only list
            }
        };
        try (Connection conn = DBConnection.getConnection();
             PreparedStatement ps = conn.prepareStatement(
                     "SELECT claim_number, policy_number, claim_amount, status, date_submitted "
                     + "FROM claims ORDER BY date_submitted DESC, claim_number DESC LIMIT 50");
             ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("claim_number"),
                    rs.getString("policy_number"),
                    rs.getBigDecimal("claim_amount"),
                    rs.getString("status"),
                    rs.getDate("date_submitted")
                });
            }
        } catch (SQLException ex) {
            showMessage("Could not load the claims list: " + ex.getMessage());
        }
        jTable2.setModel(model);
    }

