    private void applyRolePermissions() {

    // Normalize user role string to prevent mismatch bugs
    if (userRole == null || userRole.trim().isEmpty()) {
        userRole = "";
    } else {
        userRole = userRole.trim().toUpperCase();
    }

    // 2. Strictly apply role rules as per exam paper requirements
    switch (userRole) {
            case "INSURANCE_OFFICER" -> {
                jButton1.setEnabled(true); 
                jButton1.setText("Manage Customers");
                
                jButton2.setEnabled(true); 
                jButton2.setText("Create & Manage Policies");
                
                jButton3.setEnabled(true); 
                jButton3.setText("Submit Claims");
                
                jButton4.setEnabled(true); 
                jButton4.setText("Generate Reports");
            }
                
            case "CLAIMS_OFFICER" -> {
                jButton1.setEnabled(false);
                jButton1.setText("Manage Customers");
                
                jButton2.setEnabled(false);
                jButton2.setText("Create & Manage Policies");
                
                // Claims Officer: Views pending claims, assesses, approves or rejects claims
                jButton3.setEnabled(true); 
                jButton3.setText("Assess Claims");
                
                jButton4.setEnabled(false);
                jButton4.setText("Generate Reports");
            }
                
            case "ADMINISTRATOR" -> {
                // Administrator: Manages users, views system information, customers, policies, and claims, generates reports
                jButton1.setEnabled(true); 
                jButton1.setText("Manage System Users"); // Admin role feature
                
                jButton2.setEnabled(true); 
                jButton2.setText("View All Policies");
                
                jButton3.setEnabled(true); 
                jButton3.setText("View All Claims");
                
                jButton4.setEnabled(true); 
                jButton4.setText("Generate Reports");
                
                

                setupAdminPanel(); // adds "View All Customers" and "System Information"

            }
            
            
        default -> {
            // Fallback safety: if role is unknown, keep everything locked down except reports
            javax.swing.JOptionPane.showMessageDialog(this, "Warning: Unrecognized user role '" + userRole + "'. Access restricted.");
        }
    }
    }
