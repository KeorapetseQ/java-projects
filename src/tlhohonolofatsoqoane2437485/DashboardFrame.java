   public void exportClaimsReportToCSV() {
        String filePath = "Claims_Report.csv";
        String query = "SELECT claim_number, policy_number, customer_id, claim_amount, status, approved_amount FROM claims";

        try (java.io.PrintWriter writer = new java.io.PrintWriter(new java.io.File(filePath));
             java.sql.Connection conn = DBConnection.getConnection();
             java.sql.Statement stmt = conn.createStatement();
             java.sql.ResultSet rs = stmt.executeQuery(query)) {

            writer.println("ClaimNumber,PolicyNumber,CustomerID,ClaimAmount,Status,ApprovedAmount");

            while (rs.next()) {
                writer.print(rs.getString("claim_number") + ",");
                writer.print(rs.getString("policy_number") + ",");
                writer.print(rs.getString("customer_id") + ",");
                writer.print(rs.getDouble("claim_amount") + ",");
                writer.print(rs.getString("status") + ",");
                writer.println(rs.getDouble("approved_amount"));
            }

        } catch (Exception e) {
            System.err.println("Error exporting claims report: " + e.getMessage());
        }
    }
   
