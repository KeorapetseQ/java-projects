    private void openViewer(String viewTitle, String sql) {
    javax.swing.JFrame viewerFrame = new javax.swing.JFrame(viewTitle);  
    viewerFrame.setDefaultCloseOperation(javax.swing.WindowConstants.DISPOSE_ON_CLOSE);
    viewerFrame.setSize(750, 400);
    viewerFrame.setLocationRelativeTo(this);
        
    javax.swing.JTable table = new javax.swing.JTable();
    table.setDefaultEditor(Object.class, null); // read-only
    DefaultTableModel model = new DefaultTableModel();
        
        try (Connection conn = DBConnection.getConnection();
             Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery(sql)) { // Uses the passed parameter sqlQuery correctly
            
            ResultSetMetaData meta = rs.getMetaData();
            int columnCount = meta.getColumnCount();
            
            for (int i = 1; i <= columnCount; i++) {
                model.addColumn(meta.getColumnLabel(i));
            }
            
            while (rs.next()) {
                Object[] row = new Object[columnCount];
                for (int i = 1; i <= columnCount; i++) {
                    row[i - 1] = rs.getObject(i);
                }
                model.addRow(row);
            }
            table.setModel(model);
        } catch (SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Database Query Error: " + e.getMessage());
            return;
        }
        
        viewerFrame.add(new javax.swing.JScrollPane(table));
        viewerFrame.setVisible(true);
    }


    
