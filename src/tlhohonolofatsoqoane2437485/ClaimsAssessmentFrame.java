        private void initTableSelectionListener() {
        jTable1.getSelectionModel().addListSelectionListener(event -> {
            if (!event.getValueIsAdjusting() && jTable1.getSelectedRow() != -1) {
                int selectedRow = jTable1.getSelectedRow();
                jTextField2.setText(jTable1.getValueAt(selectedRow, 0).toString()); // Claim Number
                jTextField1.setText(jTable1.getValueAt(selectedRow, 2).toString()); // Claim Amount
                jTextField4.setText(jTable1.getValueAt(selectedRow, 3).toString()); // Status
            }
        });
    }
    
    private void loadClaimsTableData() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0); // Clear existing rows

        String query = "SELECT claim_number, policy_number, claim_amount, status FROM claims";

        try (Connection conn = DBConnection.getConnection();
             Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery(query)) {

            while (rs.next()) {
                Object[] row = {
                    rs.getString("claim_number"),
                    rs.getString("policy_number"),
                    rs.getDouble("claim_amount"),
                    rs.getString("status")
                };
                model.addRow(row);
            }
        } catch (SQLException e) {
            System.err.println("Error loading claims table: " + e.getMessage());
        }
    }

