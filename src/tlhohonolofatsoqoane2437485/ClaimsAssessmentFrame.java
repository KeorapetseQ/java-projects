    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String claimNumber = jTextField2.getText().trim();
        String status = jTextField4.getText().trim().toUpperCase(); // e.g., APPROVED, REJECTED, UNDER_REVIEW
        String approvedAmountStr = jTextField5.getText().trim();
        String rejectionReason = jTextField6.getText().trim();

        if (claimNumber.isEmpty() || status.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select a claim and provide a status!");
            return;
        }
        
        
       double approvedAmount = 0.0;
        try {
            if (!approvedAmountStr.isEmpty()) {
                approvedAmount = Double.parseDouble(approvedAmountStr);
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Invalid approved amount format!");
            return;
        }
    
    String sql = "UPDATE claims SET status = ?, approved_amount = ?, rejection_reason = ? WHERE claim_number = ?";

        try (Connection conn = DBConnection.getConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql)) {
            
            pstmt.setString(1, status);
            pstmt.setDouble(2, approvedAmount);
            pstmt.setString(3, rejectionReason.isEmpty() ? null : rejectionReason);
            pstmt.setString(4, claimNumber);

            int rowsUpdated = pstmt.executeUpdate();
            if (rowsUpdated > 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Claim assessment saved successfully!");
                
                // Trigger background email notification requirement for status change
                new Thread(() -> {
                    EmailService.sendEmailForClaimStatus(claimNumber, status);
                }).start();

                // Clear fields and refresh table
                jTextField2.setText("");
                jTextField1.setText("");
                jTextField3.setText("");
                jTextField4.setText("");
                jTextField5.setText("");
                jTextField6.setText("");
                loadClaimsTableData();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Claim not found in database.");
            }

        } catch (SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

