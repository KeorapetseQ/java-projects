    private void loadCustomerTableData() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0); // Clear existing table rows

        String query = "SELECT first_name, surname, national_id, email FROM Customers";

        try (Connection conn = DBConnection.getConnection();
             Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery(query)) {

            while (rs.next()) {
                Object[] row = {
                    rs.getString("first_name"),
                    rs.getString("surname"),
                    rs.getString("national_id"),
                    rs.getString("email")
                };
                model.addRow(row);
            }
        } catch (SQLException e) {
            System.err.println("Error loading customer table: " + e.getMessage());
        }
    }
