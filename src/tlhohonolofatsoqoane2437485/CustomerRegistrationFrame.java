    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
                                        
    String firstName = jTextField1.getText().trim();
    String surname = jTextField2.getText().trim();
    String nationalId = jTextField3.getText().trim();
    String dob = jTextField4.getText().trim();
    
    String gender = "Other";
    if (jRadioButton1.isSelected()) gender = "Male";
    else if (jRadioButton2.isSelected()) gender = "Female";
    
    String phone = jTextField5.getText().trim();
    String email = jTextField6.getText().trim();
    String address = jTextArea1.getText().trim();

    if (firstName.isEmpty() || surname.isEmpty() || nationalId.isEmpty() || email.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please fill in all required customer fields!");
        return;
    }

    CustomerDAO dao = new CustomerDAO();
    boolean success = dao.registerCustomer(firstName, surname, nationalId, dob, gender, phone, email, address);

    if (success) {
        javax.swing.JOptionPane.showMessageDialog(this, "Customer registered successfully!");
        // Trigger Email Notification requirement
        new Thread(() -> {
                EmailService.sendEmail(email, "Welcome to UbuntuSure Insurance", 
                    "Dear " + firstName + ",\n\nYour profile has been successfully registered with UbuntuSure.\nThank you for choosing us!");
            }).start();

        // Clear fields
        jTextField1.setText(""); jTextField2.setText(""); jTextField3.setText("");
        jTextField4.setText(""); jTextField5.setText(""); jTextField6.setText("");
        jTextArea1.setText("");
        jRadioButton1.setSelected(true);
        
        loadCustomerTableData();
        
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Error saving customer. Check National ID uniqueness.");
    }

    }//GEN-LAST:event_jButton1ActionPerformed

