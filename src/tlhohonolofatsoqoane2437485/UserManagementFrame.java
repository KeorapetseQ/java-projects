    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    String full_name = JOptionPane.showInputDialog(this, "Enter Full Name:");
    if (full_name == null || full_name.trim().isEmpty()) return;
    
    // 3. Prompt for Email
        String email = JOptionPane.showInputDialog(this, "Enter Email:");
        if (email == null || email.trim().isEmpty()) return;

    String password = JOptionPane.showInputDialog(this, "Enter Password:");
    if (password == null || password.trim().isEmpty()) return;

    String[] roles = {"ADMINISTRATOR", "CLAIMS_OFFICER", "INSURANCE_OFFICER"};
    String role = (String) JOptionPane.showInputDialog(
        this, "Select User Role:", "Role Assignment",
        JOptionPane.QUESTION_MESSAGE, null, roles, roles[2]);

    if (role != null) {
        String sql = "INSERT INTO users (full_name, email, password_hash, role) VALUES (?, ?, ?, ?)";
        try (Connection conn = DBConnection.getConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql)) {
            pstmt.setString(1, full_name.trim());
            pstmt.setString(2, email.trim());
            pstmt.setString(3, password.trim());
            pstmt.setString(4, role);
            pstmt.executeUpdate();
            JOptionPane.showMessageDialog(this, "User added successfully!");
            loadUsersTable();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error adding user: " + e.getMessage());
        }}
    
    }//GEN-LAST:event_jButton1ActionPerformed

