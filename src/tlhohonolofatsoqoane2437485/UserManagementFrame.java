    private void loadUsersTable() {
        DefaultTableModel model = (DefaultTableModel) TableUsers.getModel();
        model.setColumnIdentifiers(new String[]{"User ID", "full_name", "Role"}); // Set proper column headers
        model.setRowCount(0); // Clear table before reloading

        String query = "SELECT user_id, full_name, role FROM users";
        try (Connection conn = DBConnection.getConnection();
             Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery(query)) {

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("user_id"),
                    rs.getString("full_name"),
                    rs.getString("role")
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading users from database: " + e.getMessage());
        }
    }
    
